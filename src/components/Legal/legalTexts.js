// Юр-документы платформы и витрин (структура — как legalDocs.js в anyforms:
// { title, updated?, intro, sections: [{ heading, paragraphs }] }).
//
// В anyforms тексты были статичными под одного продавца. Здесь витрин много и у
// каждой свой продавец, поэтому документы витрины — шаблоны, в которые
// подставляются реквизиты мерчанта из PublicShopDTO. Продавец и оператор
// персональных данных покупателей — сам мерчант; платформа только даёт
// технические средства (витрина, корзина, передача на оплату в банк мерчанта).
//
// Формулировки намеренно общие и консервативные: никаких фактов о продавце,
// которых он сам не указал (система налогообложения, сроки отправки, адреса
// серверов и т. п.). Незаполненное поле выводим как «не указан(о)».
// Перед запуском в прод тексты должен вычитать юрист владельца платформы.
/* eslint-disable max-len */
import { BRAND_NAME, PLATFORM_OPERATOR } from '../../config/brand';

// Редакция шаблона политики платформы. Документы витрин без даты редакции:
// их содержание меняется вместе с реквизитами, которые мерчант правит сам.
const PLATFORM_PRIVACY_UPDATED = '1 октября 2026 г.';

const clean = (value) => (typeof value === 'string' ? value.trim() : '');
const orMissing = (value, missing = 'не указан') => clean(value) || missing;

// ОГРН — 13 цифр (организация), ОГРНИП — 15 (индивидуальный предприниматель).
const ogrnLabel = (ogrn) => {
  const digits = clean(ogrn).replace(/\D/g, '');
  if (digits.length === 15) return 'ОГРНИП';
  if (digits.length === 13) return 'ОГРН';
  return 'ОГРН/ОГРНИП';
};

const origin = () => (typeof window !== 'undefined' ? window.location.origin : '');

const shopUrl = (slug) => `${origin()}/shop/${slug}`;

// Нумерация пунктов «1.1.», «1.2.» — как в текстах anyforms. Раздел реквизитов
// (plain) идёт без номеров пунктов.
const numbered = (sections) => ({
  sections: sections.map((section, i) => ({
    heading: section.heading,
    paragraphs: section.plain
      ? section.paragraphs
      : section.paragraphs.map((p, j) => `${i + 1}.${j + 1}. ${p}`),
  })),
});

// Контакты продавца строкой: «электронная почта a@b.ru; телефон +7…; Telegram @x».
const sellerContacts = (shop) => {
  const parts = [];
  if (clean(shop.contactEmail)) parts.push(`электронная почта ${clean(shop.contactEmail)}`);
  if (clean(shop.contactPhone)) parts.push(`телефон ${clean(shop.contactPhone)}`);
  if (clean(shop.supportTelegram)) parts.push(`Telegram @${clean(shop.supportTelegram).replace(/^@/, '')}`);
  return parts.length ? parts.join('; ') : 'не указаны';
};

// «продавца — ИП Иванов Иван Иванович (ИНН …, ОГРНИП …)»: тире вместо склонения —
// наименование продавца мерчант вводит сам, просклонять его мы не можем.
// noun — слово «продавец» в нужном падеже, where — где искать реквизиты, если их нет,
// alias — как продавец называется дальше в документе («Продавец», Оператор).
const sellerClause = (shop, { noun, where, alias }) => {
  const name = clean(shop.sellerName);
  if (!name) return `${noun}, сведения о котором приведены ${where} (далее — ${alias})`;
  const ids = [
    clean(shop.sellerInn) && `ИНН ${clean(shop.sellerInn)}`,
    clean(shop.sellerOgrn) && `${ogrnLabel(shop.sellerOgrn)} ${clean(shop.sellerOgrn)}`,
  ].filter(Boolean);
  return `${noun} — ${name} (${[...ids, `далее — ${alias}`].join('; ')})`;
};

const platformOperatorClause = () => {
  const name = clean(PLATFORM_OPERATOR.name);
  return name ? ` Оператор Платформы — ${name}.` : '';
};

/** Реквизиты продавца заполнены настолько, что документы витрины имеют силу. */
export const hasSellerRequisites = (shop) =>
  Boolean(clean(shop?.sellerName) && clean(shop?.sellerInn));

const sellerRequisites = (shop) => [
  `Продавец: ${orMissing(shop.sellerName)}.`,
  `ИНН: ${orMissing(shop.sellerInn)}. ${ogrnLabel(shop.sellerOgrn)}: ${orMissing(shop.sellerOgrn)}.`,
  `Адрес: ${orMissing(shop.sellerAddress)}.`,
  `Контакты: ${sellerContacts(shop)}.`,
  `Магазин: «${shop.name}», ${shopUrl(shop.slug)}.`,
];

